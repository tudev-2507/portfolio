let language = 'en';
let onUpdate = null;
function apply(lang) {
  language = lang === 'ja' ? 'ja' : 'en';
  const phrases = COPY[language];
  document.documentElement.lang = language;
  document.title = language === 'ja' ? 'ヴー・ディン・トゥー（Dev）｜動画編集・Web開発' : 'Vũ Đình Tư (Dev) | Video Editor & Developer';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = phrases[el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const value = phrases[el.dataset.i18nHtml];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll('[data-language]').forEach(btn => {
    const selected = btn.dataset.language === language;
    btn.classList.toggle('is-active', selected);
    btn.setAttribute('aria-pressed', String(selected));
  });
  if (onUpdate) onUpdate();
}
async function countryLanguage() {
  // IP geolocation is best effort. If blocked/unavailable, default to English.
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 1800);
  try {
    const response = await fetch('https://ipwho.is/?fields=country_code', {signal: controller.signal, cache: 'no-store'});
    if (!response.ok) return 'en';
    const data = await response.json();
    return data.country_code === 'JP' ? 'ja' : 'en';
  } catch (_) {
    return 'en';
  } finally { clearTimeout(timeout); }
}
export function setLanguageChangeHandler(handler) { onUpdate = handler; }
export async function initializeLanguage() {
  document.querySelectorAll('[data-language]').forEach(btn => {
    btn.addEventListener('click', () => {
      try {localStorage.setItem('portfolio-lang', btn.dataset.language);} catch(_) {}
      apply(btn.dataset.language);
    });
  });
  let preference;
  try {preference = localStorage.getItem('portfolio-lang');} catch(_) {}
  if (preference === 'ja' || preference === 'en') { apply(preference); return; }
  apply(await countryLanguage());
}
